#!/usr/bin/env bash
# ExtensionKit license server — one-command installer for a Linux VPS.
#
#   curl -fsSL https://raw.githubusercontent.com/difeizheng/extensionkit/main/deploy/install.sh | sudo bash
#
# What it does: clones the repo to /opt/extensionkit, generates real secrets,
# writes a hardened systemd unit, starts the server, and waits for /healthz.
# It never overwrites an existing .env (your secrets survive upgrades).
#
# Overrides (env vars): EXTENSIONKIT_REPO, EXTENSIONKIT_DIR, PORT, NODE_BIN

set -euo pipefail

REPO="${EXTENSIONKIT_REPO:-https://github.com/difeizheng/extensionkit.git}"
INSTALL_DIR="${EXTENSIONKIT_DIR:-/opt/extensionkit}"
DATA_DIR="${EXTENSIONKIT_DATA_DIR:-/var/lib/extensionkit}"
PORT="${PORT:-8787}"
SERVICE_NAME="extensionkit-server"
SERVER_DIR="$INSTALL_DIR/server"

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[33m[warn]\033[0m %s\n' "$*" >&2; }
die() { printf '\033[31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

# --- root -------------------------------------------------------------------
if [ "$(id -u)" -ne 0 ]; then
  command -v sudo >/dev/null 2>&1 || die "need root: re-run with sudo"
  say "Re-running with sudo"
  exec sudo -E bash "$0" "$@"
fi

# --- prerequisites ----------------------------------------------------------
command -v git >/dev/null 2>&1 || die "git is required: apt-get install -y git"
command -v curl >/dev/null 2>&1 || die "curl is required: apt-get install -y curl"

NODE_BIN="${NODE_BIN:-$(command -v node || true)}"
if [ -z "$NODE_BIN" ]; then
  die "Node.js >= 22.5 not found (node:sqlite is required).
  Install it, then re-run this script. Fastest on Debian/Ubuntu:
    curl -fsSL https://deb.nodesource.com/setup_22.x | sudo -E bash - && sudo apt-get install -y nodejs
  Or use the Docker path instead: deploy/docker-compose.yml"
fi

node_major="$("$NODE_BIN" -p 'process.versions.node.split(".")[0]')"
node_minor="$("$NODE_BIN" -p 'process.versions.node.split(".")[1]')"
if [ "$node_major" -lt 22 ] || { [ "$node_major" -eq 22 ] && [ "$node_minor" -lt 5 ]; }; then
  die "Node $("$NODE_BIN" -v) is too old — need >= 22.5 for node:sqlite."
fi
say "Node $("$NODE_BIN" -v) at $NODE_BIN"

# --- fetch code -------------------------------------------------------------
mkdir -p "$INSTALL_DIR" "$DATA_DIR"
if [ -d "$INSTALL_DIR/.git" ]; then
  say "Updating existing checkout in $INSTALL_DIR"
  git -C "$INSTALL_DIR" pull --ff-only
else
  say "Cloning $REPO into $INSTALL_DIR"
  git clone --depth 1 "$REPO" "$INSTALL_DIR"
fi

# --- config -----------------------------------------------------------------
ENV_FILE="$SERVER_DIR/.env"
if [ -f "$ENV_FILE" ]; then
  warn "$ENV_FILE exists — keeping your existing secrets"
else
  say "Generating secrets"
  gen() { "$NODE_BIN" -e "console.log(require('crypto').randomBytes(32).toString('hex'))"; }
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
LICENSE_SECRET=$(gen)
ADMIN_KEY=$(gen)
STRIPE_WEBHOOK_SECRET=
PORT=$PORT
MAX_ACTIVATIONS_PER_KEY=3
TOKEN_TTL_DAYS=7
GRACE_DAYS=3
DB_FILE=$DATA_DIR/licenses.db
RATE_LIMIT_ACTIVATE_PER_MIN=10
RATE_LIMIT_VALIDATE_PER_MIN=120
RATE_LIMIT_DEACTIVATE_PER_MIN=30
RATE_LIMIT_ADMIN_PER_MIN=120
TRUST_PROXY=0
EOF
  chmod 600 "$ENV_FILE"
  say "Wrote $ENV_FILE (secrets are yours — back this file up)"
fi

# --- systemd ----------------------------------------------------------------
UNIT=/etc/systemd/system/$SERVICE_NAME.service
say "Writing systemd unit $UNIT"
cat > "$UNIT" <<EOF
[Unit]
Description=ExtensionKit license server
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$SERVER_DIR
ExecStart=$NODE_BIN src/index.js
Restart=always
RestartSec=3
User=extensionkit
Group=extensionkit
Environment=NODE_ENV=production

# hardening: the service only needs to write its own data dir
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$DATA_DIR
ProtectKernelTunables=true
ProtectControlGroups=true
RestrictSUIDSGID=true

[Install]
WantedBy=multi-user.target
EOF

if ! id extensionkit >/dev/null 2>&1; then
  say "Creating service user 'extensionkit'"
  useradd --system --home-dir "$INSTALL_DIR" --shell /usr/sbin/nologin extensionkit
fi
chown -R extensionkit:extensionkit "$INSTALL_DIR" "$DATA_DIR"
chown extensionkit:extensionkit "$ENV_FILE"

systemctl daemon-reload
systemctl enable "$SERVICE_NAME" >/dev/null
systemctl restart "$SERVICE_NAME"

# --- wait for health --------------------------------------------------------
say "Waiting for /healthz on port $PORT"
ok=0
for _ in $(seq 1 20); do
  if curl -fsS "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1; then ok=1; break; fi
  sleep 1
done

if [ "$ok" -eq 1 ]; then
  say "Server is up: $(curl -fsS "http://127.0.0.1:$PORT/healthz")"
else
  warn "Health check did not pass. Inspect: journalctl -u $SERVICE_NAME -n 50 --no-pager"
  exit 1
fi

cat <<EOF

Next steps
  1. HTTPS is mandatory (keys travel over the network). Put it behind Caddy:
       license.yourdomain.com {
           reverse_proxy 127.0.0.1:$PORT
       }
     Caddy fetches a free certificate automatically.
  2. Set STRIPE_WEBHOOK_SECRET in $ENV_FILE, then: systemctl restart $SERVICE_NAME
  3. Point your extension at https://license.yourdomain.com and add that origin
     to host_permissions in manifest.json.
  4. Admin panel (Pro pack): open admin/dashboard.html from your server dir.
  5. Back up $ENV_FILE and $DATA_DIR/licenses.db — those two files are the business.

Useful commands
  systemctl status $SERVICE_NAME
  journalctl -u $SERVICE_NAME -f
  systemctl restart $SERVICE_NAME
EOF
